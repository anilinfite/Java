package Day6;
public class Data {
    // Integer types cam be represented in different types
    public static void main(String[] args)
    {
        byte b1 = 10; // decimal
        byte b2 = 0b1010; // byte range from -128 to 127 we can give number // binary
        byte b3 = 012; // octal
        byte b4 = 0xA; // Hexadecimal 

        System.out.println(b1);
        System.out.println(b2);
        System.out.println(b3);
        System.out.println(b4);
    }
}

