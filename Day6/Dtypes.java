package Day6;
public class Dtypes {
    public static void main(String[] args) {
        byte bytevalue = 10; // 1byte and range --> -128 to 127
        short shortvalue = 120; // 2bytes and range --> -32768 to 32767
        int intvalue = 20520250; 
        long longvalue = 90000000000L;
       
       //float value pi value 3.14
        float floatvalue = 3.14f;
        double doublevalue = 3.142857698754;

        char charvalue = 'A';
        boolean booleanvalue = true;

        String stringvalue = "Algorithms";

        System.out.println("Bytevalue : " + bytevalue);
        System.out.println("shortvalue : " + shortvalue);
        System.out.println("integervalue : " + intvalue);
        System.out.println("longvalue : " + longvalue);

        System.out.println();

        System.out.println("floatvalue : " + floatvalue);
        System.out.println("doublevalue : " + doublevalue);

        System.out.println();

        System.out.println("Charvalue : " + charvalue);
        System.out.println("booleanvalue : " + booleanvalue);
     
        System.out.println("Stringvalue : " + stringvalue);
        

    }
}
